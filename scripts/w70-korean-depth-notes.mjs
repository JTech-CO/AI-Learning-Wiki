export function buildDepthNote(topic, sectionIndex) {
  const profile = profiles[topic.id];
  if (!profile || profile.length !== 6) throw new Error(`${topic.id}: six depth anchors are required.`);
  return variants[sectionIndex](topic, profile[sectionIndex]);
}

